function img(fn, w=540, h=380) {
    try {
        const data = fs.readFileSync(path.join(CHARTS, fn));
        return new Paragraph({
            children: [new ImageRun({ type:'png', data, transformation:{width:w, height:h},
                altText:{title:fn, description:fn, name:fn} })],
            alignment: AlignmentType.CENTER, spacing:{after:200}
        });
    } catch(e) { return new Paragraph({children:[new TextRun({text:`[Chart: ${fn}]`, color:'999'})]}); }
}

function h1(t) { return new Paragraph({ heading:HeadingLevel.HEADING_1, children:[new TextRun({text:t, bold:true, font:'Arial', size:32})], spacing:{before:400, after:200} }); }
function h2(t) { return new Paragraph({ heading:HeadingLevel.HEADING_2, children:[new TextRun({text:t, bold:true, font:'Arial', size:26})], spacing:{before:300, after:160} }); }
function h3(t) { return new Paragraph({ heading:HeadingLevel.HEADING_3, children:[new TextRun({text:t, bold:true, font:'Arial', size:24})], spacing:{before:200, after:120} }); }
function p(t, o={}) { return new Paragraph({ children:[new TextRun({text:t, font:'Arial', size:22, ...o})], spacing:{after:120} }); }
function bold(t) { return p(t, {bold:true}); }
function pb() { return new Paragraph({children:[new PageBreak()]}); }
function sp(before=0) { return new Paragraph({spacing:{before, after:0}, children:[]}); }

// Table helper
function dataTable(headers, rows, colWidths) {
    const border = {style:BorderStyle.SINGLE, size:1, color:'BBBBBB'};
    const borders = {top:border, bottom:border, left:border, right:border};
    const hdrShading = {fill:'2C3E50', type:ShadingType.CLEAR};
    
    const hdrCells = headers.map((h, i) => new TableCell({
        borders, shading: hdrShading,
        width:{size:colWidths[i], type:WidthType.DXA},
        margins:{top:60, bottom:60, left:80, right:80},
        children:[new Paragraph({children:[new TextRun({text:h, font:'Arial', size:20, bold:true, color:'FFFFFF'})]})]
    }));
    
    const dataRows = rows.map((row, ri) => new TableRow({
        children: row.map((cell, i) => new TableCell({
            borders,
            shading: ri % 2 === 0 ? {fill:'F8F9FA', type:ShadingType.CLEAR} : undefined,
            width:{size:colWidths[i], type:WidthType.DXA},
            margins:{top:50, bottom:50, left:80, right:80},
            children:[new Paragraph({children:[new TextRun({text:String(cell), font:'Arial', size:20})]})]
        }))
    }));
    
    return new Table({
        width:{size: colWidths.reduce((a,b)=>a+b,0), type:WidthType.DXA},
        columnWidths: colWidths,
        rows: [new TableRow({children:hdrCells}), ...dataRows]
    });
}

// Quote/callout helper
function callout(text) {
    return new Paragraph({
        children:[new TextRun({text:'💡 '+text, font:'Arial', size:22, italics:true, color:'2C3E50'})],
        spacing:{before:160, after:160},
        indent:{left:400},
        border:{left:{style:BorderStyle.SINGLE, size:6, color:'3498DB', space:8}}
    });
}

